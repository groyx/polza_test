"""
Добыча фактов для персонализации — детерминированно, без модели.

Почему это отдельный модуль, а не пара строк внутри персонализации.
Качество холодного письма упирается ровно в одно: насколько конкретен
факт в первой строке. «Вы производите оборудование» не работает —
это верно для половины базы. «Листогибочные прессы до 400 тонн»
работает, потому что верно только для одного адресата.

Значит задача не «сделать красивое предложение», а **найти самый
конкретный проверяемый факт из того, что удалось скачать**, и уже потом
его оформить. Ранжирование здесь важнее формулировки.

Лестница приоритета — от самого сильного к слабому:

  1. news      свежая новость с сайта. Повод «прямо сейчас».
  2. product   конкретная продуктовая линейка из заголовков.
  3. scale     город производства, год основания, цифры масштаба.
  4. profile   чем компания занимается, из описания сайта.
  5. hiring    открытая вакансия продажника — только как запасной вариант.
  -            ничего конкретного нет -> факта нет, ячейка пустая.

Почему вакансия внизу, хотя как сигнал она сильнейшая. Сигнал найма
отвечает на вопрос «зачем мы вообще пишем», и в цепочке он уже стоит
отдельной строкой в первом письме. Если положить его ещё и в
{{персонализация}}, вся база получит одинаковый текст «вижу, вы ищете
менеджера по продажам» — то есть ровно тот шаблон, которого мы избегаем.
Проверено на прогоне: с вакансией на первом месте восемь строк из восьми
вышли идентичными. Персонализация обязана различать адресатов, поэтому
наверху стоит то, что уникально для конкретного сайта.

Каждый факт несёт источник и дословную цитату. Это не украшение:
цитата позволяет проверить любую строку базы за пятнадцать секунд и
делает невозможным незаметное враньё.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from site_scrape import SiteData

# Дежурные фразы, которые есть на каждом втором сайте. Персонализацией
# не являются и в письме читаются как явный шаблон.
BORING = re.compile(
    r"новым годом|8 марта|23 февраля|день победы|праздничн|поздравля|"
    r"график работы|режим работы|политика конфиденциальност|"
    r"использует cookie|все права защищены|обратный звонок|"
    r"подпишитесь|подписаться|рассылк|акци[яи]\b|скидк|распродаж|"
    r"справка для|пресс-релиз|вакансии компании|"
    # Пункты меню, которые лезут в блок новостей и новостью не являются.
    r"^блог|полезные стать|все новости|читать далее|смотреть все|"
    # Кнопки и формы. Формы склоняются, поэтому корни, а не точные фразы:
    # в вёрстке встречается и «обратный звонок», и «заказ обратного звонка».
    r"обратн\w+ звон|заказать звон|оставить заявк|оставьте заявк|"
    r"напишите нам|свяжитесь с нами|задать вопрос|перезвон|"
    r"подобрать|рассчитать стоимость|узнать цену|"
    # Маркетинговый шум: розыгрыши и конкурсы не характеризуют компанию.
    r"разыгрыва|розыгрыш|конкурс\b|дарим|подар\w+ за",
    re.IGNORECASE,
)

# Признак того, что заголовок описывает продукт или услугу, а не слоган.
# Набор корней настроен под текущую вертикаль базы — промышленное
# оборудование и металлообработка. При смене ниши это точка настройки:
# для условного HR-tech сюда пойдут другие слова.
PRODUCT_TERMS = re.compile(
    r"станк|оборудован|металл|прокат|труб|инструмент|деталь|детал|"
    r"поставк|производств|изготовлен|обработк|сталь|стальн|лист|профил|"
    r"машин|систем|комплект|запчаст|чпу|сварк|лить|литейн|"
    r"фрез|токарн|шлифов|пресс|насос|привод|подшипник|"
    r"монтаж|проектирован|сервис|ремонт|каталог|склад|"
    r"технолог|решени|услуг|продаж|аренд|логистик|склад",
    re.IGNORECASE,
)

# Общие слова: если «конкретика» состоит только из них, она не конкретика.
VAGUE = re.compile(
    r"^(о компании|о нас|главная|продукция|каталог|услуги|товары|"
    r"контакты|доставка|оплата|производство|оборудование|компания|"
    r"наши услуги|наша продукция|добро пожаловать|"
    # «Каталог оборудования» — это пункт меню, а не направление.
    # «Каталог товаров металлопроката» уже сообщает нишу, его оставляем.
    r"каталог \w+|наш каталог|весь каталог)$",
    re.IGNORECASE,
)

YEAR_RE = re.compile(
    r"(?:на рынке с|работаем с|основан[аоы]? в|с)\s*(19[5-9]\d|20[0-2]\d)\s*(?:год|г\.|г\b)",
    re.IGNORECASE,
)
# Предлог захватываем вместе с городом: от него зависит падеж. После «в»
# в тексте стоит предложный падеж («в Москве»), после «г.» — именительный
# («г. Пятигорск»). Без этого получается «производство в городе Москве».
CITY_RE = re.compile(
    r"(?:производство|завод|цех|склад|офис)\D{0,25}?"
    r"\b(в|г\.)\s*([А-ЯЁ][а-яё]{3,}(?:-[А-ЯЁ][а-яё]+)?)",
)
SCALE_RE = re.compile(
    r"(более|свыше|около)\s+(\d[\d\s]{1,8})\s+"
    r"(клиент\w*|заказчик\w*|проект\w*|сотрудник\w*|компан\w*|"
    r"наименован\w*|позиц\w*|объект\w*|дилер\w*)",
    re.IGNORECASE,
)
# Дата в заголовке новости: 12.03.2026 или «12 марта 2026»
NEWS_DATE_RE = re.compile(
    r"\b(\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}|\d{1,2}\s+"
    r"(?:январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|"
    r"ноябр|декабр)\w*\s+\d{4})\b",
    re.IGNORECASE,
)


@dataclass
class Fact:
    kind: str          # hiring | news | product | scale | profile
    rank: int          # чем меньше, тем сильнее
    text: str          # готовая фраза для письма
    quote: str         # дословная цитата-подтверждение
    source: str        # URL, откуда взято


# Декор из мета-описаний: звёздочки, эмодзи, стрелки. В SEO-описаниях их
# ставят для выдачи, в письме они выглядят как сбой кодировки.
DECOR = re.compile(
    r"[←-⇿⌀-⏿①-⓿■-➿"
    r"⬀-⯿️〰]|[\U0001F000-\U0001FAFF]"
)


def _clean(s: str) -> str:
    s = DECOR.sub(" ", s or "")
    return " ".join(s.split()).strip(" -–—|,;:")


def _usable(s: str, lo: int = 12, hi: int = 190) -> bool:
    s = _clean(s)
    return bool(s) and lo <= len(s) <= hi and not BORING.search(s) and not VAGUE.match(s)


def _dedup_phrase(s: str) -> str:
    """
    Убирает подряд идущий повтор фразы в любом месте строки.

    Вёрстка часто дублирует слоган во вложенных тегах, и после get_text
    выходит «Сага Телеком — всегда надежное решение всегда надежное
    решение». Повтор может быть не с начала строки, поэтому ищем
    совпадающие соседние n-граммы по всей длине, от длинных к коротким.
    """
    words = s.split()
    n = len(words) // 2
    while n >= 2:
        for i in range(len(words) - 2 * n + 1):
            if words[i : i + n] == words[i + n : i + 2 * n]:
                words = words[: i + n] + words[i + 2 * n :]
                n = len(words) // 2
                break
        else:
            n -= 1
    return " ".join(words)


def _quoted(s: str) -> str:
    """
    Оборачивает фразу в кавычки, сняв те, что уже есть внутри.

    Без этого выходит ««СтальЭнерго-96» — надежный поставщик»: заголовки
    на сайтах часто сами содержат кавычки вокруг названия компании.
    """
    return "«" + re.sub(r"[«»\"“”„']", "", s).strip() + "»"


def _norm_words(s: str) -> set[str]:
    return {w for w in re.findall(r"[а-яёa-z0-9]{3,}", s.lower())}


def _is_company_name(heading: str, company: str) -> bool:
    """
    Заголовок — это просто название компании?

    Считаем так, если почти все значимые слова заголовка есть в названии.
    Юрформу из названия предварительно выкидываем.
    """
    comp = _norm_words(re.sub(r"\b(ООО|АО|ЗАО|ПАО|ИП|ОАО)\b", " ", company))
    head = _norm_words(heading)
    if not head or not comp:
        return False
    return len(head - comp) <= max(0, len(head) // 4)


def mine(
    data: SiteData,
    company: str = "",
    vacancy: str = "",
    vacancy_url: str = "",
) -> list[Fact]:
    """Возвращает найденные факты, отсортированные от сильного к слабому."""
    found: list[Fact] = []
    site = data.final_url or data.url

    # --- 1. сигнал найма -------------------------------------------------
    if vacancy and _usable(vacancy, lo=6):
        v = _clean(vacancy)
        found.append(Fact(
            kind="hiring", rank=9,
            text=f"Увидел, что вы ищете человека на позицию {_quoted(v)}",
            quote=v,
            source=vacancy_url or "hh.ru",
        ))

    # --- 2. свежая новость ----------------------------------------------
    for n in data.news:
        if not _usable(n, lo=25):
            continue
        n = _clean(n)
        date = NEWS_DATE_RE.search(n)
        # Новость с датой сильнее новости без даты: видно, что сайт живой.
        found.append(Fact(
            kind="news", rank=1 if date else 2,
            text=f"У вас в новостях: {_quoted(n)}",
            quote=n,
            source=site,
        ))
        break

    # --- 3. конкретная продуктовая линейка -------------------------------
    for h in data.headings:
        h = _dedup_phrase(_clean(h))
        if not _usable(h, lo=14, hi=110):
            continue
        # Заголовок содержателен, если называет продукт или услугу, либо
        # содержит цифру — типоразмер, мощность, серию. Одного «три слова
        # и больше» мало: под это подходит любой слоган вроде «Вместе
        # достигая большего», а он про компанию ничего не сообщает.
        if not (PRODUCT_TERMS.search(h) or re.search(r"\d", h)):
            continue
        # Заголовок, который просто повторяет название компании, ничего
        # не сообщает: «Заметил у вас направление "Белоярский трубный
        # завод"» — это не наблюдение, а зачитывание вывески.
        if company and _is_company_name(h, company):
            continue
        found.append(Fact(
            kind="product", rank=3,
            text=f"Заметил у вас направление {_quoted(h)}",
            quote=h,
            source=site,
        ))
        break

    # --- 4. масштаб и география ------------------------------------------
    text = data.raw_text or data.about_text
    bits: list[tuple[str, str]] = []

    m = CITY_RE.search(text)
    if m:
        prep, city = m.group(1), m.group(2)
        where = f"в {city}" if prep == "в" else f"в городе {city}"
        bits.append((f"производство {where}", _clean(m.group(0))))
    m = YEAR_RE.search(text)
    if m:
        year = int(m.group(1))
        if 1950 <= year <= 2026:
            bits.append((f"на рынке с {year} года", _clean(m.group(0))))
    m = SCALE_RE.search(text)
    if m:
        bits.append((
            f"{m.group(1).lower()} {_clean(m.group(2))} {m.group(3).lower()}",
            _clean(m.group(0)),
        ))

    if bits:
        joined = ", ".join(b[0] for b in bits[:2])
        found.append(Fact(
            kind="scale", rank=4,
            text=f"Судя по сайту, {joined}",
            quote=" | ".join(b[1] for b in bits[:2]),
            source=site,
        ))

    # --- 5. профиль из описания ------------------------------------------
    for candidate in (data.meta_description, data.title):
        c = _clean(candidate)
        if not _usable(c, lo=35):
            continue
        # Обрезаем по границе предложения, а не по символу: обрубок
        # посреди слова в письме выглядит как сбой скрипта.
        c = re.split(r"(?<=[.!?])\s", c)[0][:160].rstrip(" ,-–—|")
        found.append(Fact(
            kind="profile", rank=5,
            text=f"Судя по описанию сайта: {c}",
            quote=_clean(candidate)[:200],
            source=site,
        ))
        break

    found.sort(key=lambda f: f.rank)
    return found


def compose(facts: list[Fact], max_len: int = 260) -> tuple[str, str, str]:
    """
    Собирает персонализацию из лучших фактов.

    Берём максимум два и обязательно разных типов: два продуктовых
    заголовка подряд читаются как выгрузка из каталога, а связка
    «вакансия + конкретика по продукту» звучит как наблюдение человека.

    Возвращает (текст, цитата, источник).
    """
    if not facts:
        return "", "", ""

    # Вторым фактом годится только то, что уникально для этого сайта.
    # profile — пересказ мета-тегов, даёт склейку «Вы занимаетесь:
    # Официальный сайт производителя...». hiring одинаков по всей базе и
    # уже стоит отдельной строкой в первом письме: если добавить его
    # сюда, персонализация снова перестанет различать адресатов.
    SITE_SPECIFIC = {"news", "product", "scale"}

    chosen = [facts[0]]
    for f in facts[1:]:
        if f.kind != chosen[0].kind and f.kind in SITE_SPECIFIC:
            chosen.append(f)
            break

    text = chosen[0].text
    if len(chosen) > 1:
        tail = chosen[1].text
        # Обе фразы могут начинаться с «Судя по сайту» — во втором
        # предложении вводное слово снимаем, иначе выходит канцелярит
        # «Судя по сайту, X. Судя по сайту, Y».
        tail = re.sub(r"^Судя по сайту,\s*", "", tail)
        tail = re.sub(r"^Заметил у вас\s*", "у вас ", tail)
        text = f"{text.rstrip('.')}. {tail[0].upper()}{tail[1:]}"
    text = text.rstrip(".") + "."

    if len(text) > max_len:
        text = chosen[0].text.rstrip(".") + "."

    return (
        text,
        " || ".join(f.quote for f in chosen),
        chosen[0].source,
    )
